    <h1>How to use this webpage</h1>
    <p class="navigation">In navigation bar, circular image icon is for <b>Profile</b> menu, 'Food Recipe' is for Food_Recipe/Home page, </p>
    <h2>Create Recipe</h2>
    <ol-1>
        <li>Go to <u>Food Recipe</u> menu</li>
        <li>Click on Add Recipe menu</li>
        <li>Enter the Ingredients' name and their quantity, Instructions and image and/or video files in their respective places</li>
        <li>Click on <b>Done</b></li>
    </ol-1>
    <h2>Edit Recipe</h2>
    <ol-1>
        <li>Go to <u>Profile</u> menu by clicking profile icon at leftmost in navigation bar</li>
        <li>Find the Food Recipe to edit in <b>My Recipes</b> table</li>
        <li>Click <em>Edit</em> icon at right hand side of the Food name</li>
        <li>Make necesssary changes to the Food Recipe information</li>
        <li>Click on <b>Done</b></li>
    </ol-1>
    <h2>Delete Recipe</h2>
    <ol-1>
        <li>Go to <u>Profile</u> menu by clicking profile icon at leftmost in navigation bar</li>
        <li>Find the Food Recipe to edit in <b>My Recipes</b> table</li>
        <li>Click <em>Delete</em> icon at right hand side of the Food name</li>
        <li>Click on "Delete" button in the dialogue box</li>
    </ol-1>
    <h2>View Recipe</h2>
    <ol-1>
        <li>Go to <u>Food Recipe</u> menu</li>
        <li>(optional)Write the food categiry and Food name to search it's recipe</li>
        <li>The food Recipes will appear in below list with food Name (and Image). Click on your desired food</li>
    </ol-1>

